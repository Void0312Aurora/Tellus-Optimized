"""Compare actual GSHHG land overlap for the three mapping boundaries.

The boundary files are generated by MappingBoundaryStudy with one fitted cube
orientation. This script reuses the pinned GSHHG masks and the existing
Lambert equal-area local contexts; it never treats spherical cap area as land
loss.
"""
from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

from gshhg_geometry import build_local_masks
from run_coverage import projected_perimeters

RADII = (50, 100, 150, 175, 200, 250, 300, 360)
ZONES = ("excluded", "quarantined")
RESOLUTIONS = ("f", "h")
COASTLINES = ("ice_front", "grounding_line")


def write_csv(path: Path, rows: list[dict[str, object]]) -> None:
    if not rows:
        raise ValueError("no mapping coverage rows")
    with path.open("w", encoding="utf-8", newline="") as output:
        writer = csv.DictWriter(output, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)


def run(cache: Path, orientation: Path, boundaries: Path, output: Path) -> None:
    metadata = json.loads(orientation.read_text(encoding="utf-8"))
    mappings = sorted(path for path in boundaries.iterdir() if path.is_dir())
    expected = {"equiangular-cube", "spherified-cube", "conformal-cube-reference"}
    if {path.name for path in mappings} != expected:
        raise ValueError("mapping boundary directories are incomplete")

    rows: list[dict[str, object]] = []
    for resolution in RESOLUTIONS:
        contexts, _ = build_local_masks(cache / f"gshhs_{resolution}.b", metadata["vertices"])
        for mapping in mappings:
            boundary = mapping / "quarantine-boundaries-32.geojson"
            regions, loop_counts = projected_perimeters(boundary, metadata, contexts)
            for coastline in COASTLINES:
                for cap in RADII:
                    for zone in ZONES:
                        surface_area = 0.0
                        land_overlap = 0.0
                        loops = 0
                        for index, context in enumerate(contexts):
                            region = regions[(cap, zone, index)]
                            overlap = context[coastline].intersection(region)
                            surface_area += region.area / 1e6
                            land_overlap += overlap.area / 1e6
                            loops += loop_counts[(cap, zone, index)]
                        rows.append({
                            "mapping": mapping.name,
                            "resolution": resolution,
                            "antarctica": coastline,
                            "cap_radius_km": cap,
                            "transition_width_km": 50,
                            "zone": zone,
                            "subdivision": 128,
                            "samples_per_edge": 32,
                            "perimeter_loops": loops,
                            "mapped_surface_area_km2": f"{surface_area:.9f}",
                            "land_envelope_overlap_km2": f"{land_overlap:.9f}",
                            "region_land_fraction": f"{land_overlap / surface_area:.9f}" if surface_area else "0.000000000",
                        })
        print(f"GSHHG {resolution}: mapping boundary intersections completed", flush=True)
    write_csv(output, rows)
    print(f"Mapping geographic comparison saved to {output}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--cache", type=Path, required=True)
    parser.add_argument("--orientation", type=Path, required=True)
    parser.add_argument("--boundaries", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    run(args.cache, args.orientation, args.boundaries, args.output)
